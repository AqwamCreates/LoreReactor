const SUMMARIZE_SYSTEM_PROMPT = "You are a concise summarizer for roleplay chat messages. Given a single chat message, produce a brief summary that preserves: character actions, key dialogue points, emotional tone, and plot-relevant details. Output ONLY the summary text with no preamble, no markdown, no quotes.";
const COMPRESS_CHUNK_PROMPT = "You are a narrative compressor for roleplay chat history. Given a chunk of conversation messages, produce a single dense paragraph that preserves: character names, key actions, dialogue substance, emotional beats, and plot progression. Write in past tense, third person. Output ONLY the compressed paragraph with no preamble, no markdown, no quotes.";
const RECURSIVE_MERGE_PROMPT = "You are a narrative merger for roleplay chat history. Given multiple summary paragraphs from consecutive conversation segments, merge them into a single coherent paragraph that preserves the chronological flow, character arcs, and plot progression. Eliminate redundancy. Write in past tense, third person. Output ONLY the merged paragraph with no preamble, no markdown, no quotes.";
const LOCATION_VISIT_MEMORY_PROMPT = "You are a reflective character in a roleplay. Below is a record of events that occurred at a specific location during your visit. Reflect on what happened there from your personal perspective. Express your memory as natural, personal thoughts. Preserve key events, conversations, emotional moments, and outcomes. Write in first person. Output ONLY your reflection with no preamble, no markdown, no quotes.";

function createAutoSummaryContext(name: string, description: string, text: string, insertionDepth = 0, tokenBudget = 512): Context {
    const now = Date.now();
    return {
        id: `auto-summary-${uuidv4()}`,
        name,
        description,
        text,
        isAutoGenerated: true,
        useBase64Encoding: false,
        insertionDepth,
        tokenBudget,
        limitLinksToSubdirectory: false,
        firstCreatedTimestamp: now,
        lastUpdatedTimestamp: now,
    } as Context;
}

export async function generateMessageSummary(
    message: HistoryMessage,
    maxTokens = 256,
    sampler?: Sampler,
    profile?: Profile,
): Promise<string | null> {
    if (message.messageType !== 'chat') return null;
    const chatMsg = message as ChatMessage;
    let text = chatMsg.textContent;
    if (!text) return null;

    text = sanitizeToolSyntax(text, chatMsg.toolExecutionResults, true);
    const stops = resolveEffectiveStopTokens(profile?.interactionDataSummarizationStopPattern, ['\n\n', '\nMessage from']);
    const prompt = `${SUMMARIZE_SYSTEM_PROMPT}\n\nMessage from ${message.character.name}:\n${text}\n\nSummary:`;

    const requestBody = buildGenericCompletionBody(prompt, maxTokens, sampler, stops);
    const bse = getBudgetStrategyEngine();
    const { text: result } = await bse.generateCompletion(requestBody);
    return result || null;
}

export async function generateCharacterMemory(
    interactionData: InteractionData,
    character: Character,
    promptBlocks: PromptBlock[],
    modelId: string,
    maxTokens = 512,
): Promise<string | null> {
    const localHistory = getLocalMessageHistory(interactionData, character);
    if (localHistory.length === 0) return null;

    const participants = interactionData.participants;
    const languageModelSampler = interactionData.profile?.characterLanguageModelSampler || character.languageModelSampler;
    const stopPattern = interactionData.profile?.characterStopPattern;

    const filteredMessages = getFilteredTextMessages(interactionData, character.id, promptBlocks);
    const knownCharacterNames = detectName(character, filteredMessages);
    const coLocatedProtagonists = getCoLocatedProtagonists(interactionData, character);
    const coLocatedParticipants = getCoLocatedParticipants(interactionData, character);

    const activeModel = getLanguageModelEngine().getContext();
    const effectiveChatTemplateKey = activeModel?.chatTemplate;
    const resolvedChatTemplate = effectiveChatTemplateKey ? getModelTemplate(effectiveChatTemplateKey) : undefined;
    const delimiters = deriveDelimiters(resolvedChatTemplate);

    const profile = interactionData.profile;
    const ctx = {
        interactionData,
        character,
        knownNames: knownCharacterNames,
        existingCharacterText: '',
        modelId,
        allPromptBlocks: promptBlocks,
        localHistory,
        participants,
        coLocatedProtagonists,
        coLocatedParticipants,
        protagonistIds: new Set(coLocatedProtagonists.map(p => p.id)),
        characterId: character.id,
        characterParticipantId: participants.findIndex(p => p.id === character.id),
        characterParticipantTag: getParticipantTag(character, participants),
        characterName: character.name,
        profile,
        tools: getEnabledTools(character, profile),
        participantScopeModes: profile?.participantScopeModes ?? { 'Character Name': 'coLocated', 'System Prompt': 'coLocated', 'Think Prompt': 'coLocated' },
        participantInsertionModes: profile?.participantInsertionModes ?? { 'Character Name': 'dynamic', 'System Prompt': 'dynamic', 'Think Prompt': 'dynamic' },
        participantsKnownNamesLimits: profile?.participantsKnownNamesLimits ?? { 'Character Name': -1, 'System Prompt': -1, 'Think Prompt': -1 },
        minimalVolatileCacheMode: profile?.minimalVolatileCacheMode ?? false,
        currentLocation: undefined,
        currentLocationId: undefined,
        characterIdArray: [] as string[],
        textContentArray: [] as string[],
        combinationCache: {},
        numberOfMessagesByParticipant: localHistory.filter(msg => msg.character.id === character.id && msg.messageType === 'chat').length,
        delimiters,
    };

    const { chatHistoryArray } = await createChatHistoryArray(ctx);
    const participantTag = ctx.characterParticipantTag;

    let recentExpression = 'neutral';
    for (let i = localHistory.length - 1; i >= 0; i--) {
        const msg = localHistory[i];
        if (msg.character.id === character.id && msg.characterExpression) {
            recentExpression = msg.characterExpression;
            break;
        }
    }

    const memoryPromptTemplate = character.memoryPrompts?.[recentExpression] || character.memoryPrompts?.['neutral'];
    const systemDefaultPerspective = `I am ${participantTag}. I am reflecting on what I have experienced. I will express my memory as natural, personal thoughts that others will not hear, read or respond to. I will use this memory in the future. Only I can access this memory. When referring to other participants, I will identify them by their tag (e.g. 'Character 1', 'Character 2') to keep my memory records accurate.`;

    const finalMemoryInstruction = memoryPromptTemplate 
        ? resolveInnerText(memoryPromptTemplate, ctx, delimiters)
        : systemDefaultPerspective;

    const perspectiveInstruction = `${delimiters.blockStart('system')}${finalMemoryInstruction}${delimiters.blockEnd}`;
    const systemPrompt = character.systemPrompt ? `${delimiters.blockStart('system')}System Prompt: ${resolveInnerText(character.systemPrompt, ctx, delimiters)}${delimiters.blockEnd}` : '';
    const thinkPrompt = character.thinkPrompt ? `${delimiters.blockStart('system')}Think Prompt: ${resolveInnerText(character.thinkPrompt, ctx, delimiters)}${delimiters.blockEnd}` : '';

    const prompt = [systemPrompt, thinkPrompt, `${delimiters.blockStart('system')}The Start Of My Memory${delimiters.blockEnd}`, chatHistoryArray.join('\n'), `${delimiters.blockStart('system')}The End Of My Memory${delimiters.blockEnd}`, perspectiveInstruction, delimiters.turnStart(participantTag)].filter(Boolean).join('\n\n');
    const stops = resolveEffectiveStopTokens(stopPattern);

    const requestBody = buildGenericCompletionBody(prompt, maxTokens, languageModelSampler, stops);
    const bse = getBudgetStrategyEngine();
    const { text } = await bse.generateCompletion(requestBody);
    if (!text) return null;

    return tokenizeMemoryContent(text, participants);
}

export async function generateMissingSummaries(
    interactionData: InteractionData,
    character: Character,
    promptBlocks: PromptBlock[],
    windowSize: number,
    modelId: string,
    maxTokens = 256,
): Promise<Map<string, string>> {
    const results = new Map<string, string>();
    const history = getLocalMessageHistory(interactionData, character);
    const chatMessages = history.filter((m): m is ChatMessage => m.messageType === 'chat');

    const filterFlags = getUniversalMessageFilterFlags(chatMessages, promptBlocks, interactionData.contexts || [], interactionData.locations || []);
    const cutoff = Math.max(0, history.length - windowSize);
    const toSummarize: ChatMessage[] = [];

    for (let i = 0; i < cutoff; i++) {
        const msg = history[i];
        if (msg.messageType !== 'chat') continue;
        const chatIdx = chatMessages.indexOf(msg as ChatMessage);
        if (chatIdx >= 0 && filterFlags[chatIdx]) continue;
        if ((msg as ChatMessage).modelTextContentSummaries?.[modelId]) continue;
        if (!(msg as ChatMessage).textContent) continue;
        toSummarize.push(msg as ChatMessage);
    }

    if (toSummarize.length === 0) return results;

    const profile = interactionData.profile;
    for (const msg of toSummarize) {
        const summary = await generateMessageSummary(msg, maxTokens, profile?.interactionDataSummarizationSampler, profile);
        if (summary) results.set(msg.id, summary);
    }
    return results;
}

async function compressChunk(messages: HistoryMessage[], maxTokens = 512, sampler?: Sampler, profile?: Profile): Promise<string | null> {
    const chatMessages = messages.filter((m): m is ChatMessage => m.messageType === 'chat' && !!(m as ChatMessage).textContent);
    if (chatMessages.length === 0) return null;

    const formatted = chatMessages.map(m => `${m.character.name}: ${sanitizeToolSyntax(m.textContent, m.toolExecutionResults, true)}`).join('\n\n');
    const stops = resolveEffectiveStopTokens(profile?.interactionDataSummarizationStopPattern);
    const prompt = `${COMPRESS_CHUNK_PROMPT}\n\nConversation chunk:\n${formatted}\n\nCompressed paragraph:`;

    const requestBody = buildGenericCompletionBody(prompt, maxTokens, sampler, stops);
    const bse = getBudgetStrategyEngine();
    const { text } = await bse.generateCompletion(requestBody);
    return text || null;
}

export async function generateLocationVisitSummary(
    interactionData: InteractionData,
    character: Character,
    promptBlocks: PromptBlock[],
    modelId: string,
    locationId: string,
    nextLocationId: string | undefined,
    startIdx: number,
    endIdx: number,
    maxTokens = 512,
): Promise<string | null> {
    const history = getGlobalMessageHistory(interactionData);
    if (startIdx < 0 || endIdx >= history.length || startIdx > endIdx) return null;

    const participants = interactionData.participants;
    const participantTag = getParticipantTag(character, participants);
    const filteredMessages = getFilteredTextMessages(interactionData, character.id, promptBlocks);
    const knownCharacterNames = detectName(character, filteredMessages);

    const activeModel = getLanguageModelEngine().getContext();
    const delimiters = deriveDelimiters(activeModel?.chatTemplate ? getModelTemplate(activeModel.chatTemplate) : undefined);

    const scopedMessages: string[] = [];
    for (let i = startIdx; i <= endIdx; i++) {
        const msg = history[i];
        if (msg.messageType !== 'chat') continue;
        const chatMsg = msg as ChatMessage;
        if (!chatMsg.textContent) continue;
        const pIdx = participants.findIndex(p => p.id === chatMsg.character.id);
        const tag = pIdx !== -1 ? `Character ${pIdx + 1}` : 'Unknown';
        const rawText = chatMsg.modelTextContentSummaries?.[modelId] || chatMsg.textContent;
        const cleanText = sanitizeToolSyntax(rawText, chatMsg.toolExecutionResults, true);
        scopedMessages.push(`${delimiters.turnStart(`${tag} (${chatMsg.character.name})`)}${cleanText}${delimiters.turnEnd}`);
    }

    if (scopedMessages.length === 0) return null;

    const locs = interactionData.locations;
    const locationName = locs.find(l => l.id === locationId)?.name || 'an unknown location';
    const nextLocationName = nextLocationId ? locs.find(l => l.id === nextLocationId)?.name : undefined;
    const coLocatedProtagonists = getCoLocatedProtagonists(interactionData, character);

    const dummyCtx = {
        characterParticipantTag: participantTag,
        characterName: character.name,
        coLocatedProtagonists,
        participants,
        knownNames: knownCharacterNames,
        tools: getEnabledTools(character, interactionData.profile),
        delimiters
    } as any;

    const systemPrompt = character.systemPrompt ? `${delimiters.blockStart('system')}System Prompt: ${resolveInnerText(character.systemPrompt, dummyCtx, delimiters)}${delimiters.blockEnd}` : '';
    const thinkPrompt = character.thinkPrompt ? `${delimiters.blockStart('system')}Think Prompt: ${resolveInnerText(character.thinkPrompt, dummyCtx, delimiters)}${delimiters.blockEnd}` : '';
    const scopedHistoryBlock = `${delimiters.blockStart('system')}Events at ${locationName}:\n${scopedMessages.join('\n')}${delimiters.blockEnd}`;

    let recentExpression = 'neutral';
    for (let i = endIdx; i >= 0; i--) {
        const msg = history[i];
        if (msg.character.id === character.id && msg.characterExpression) {
            recentExpression = msg.characterExpression;
            break;
        }
    }

    const memoryPromptTemplate = character.memoryPrompts?.[recentExpression] || character.memoryPrompts?.['neutral'];
    const systemDefaultPerspective = nextLocationName 
        ? `I am ${participantTag}. I am reflecting on what happened at ${locationName} before I moved to ${nextLocationName}. ${LOCATION_VISIT_MEMORY_PROMPT} I will never use 'Character #' or 'Character # (Name)' unless I require it.`
        : `I am ${participantTag}. ${LOCATION_VISIT_MEMORY_PROMPT} I will never use 'Character #' or 'Character # (Name)' unless I require it.`;

    const finalMemoryInstruction = memoryPromptTemplate ? resolveInnerText(memoryPromptTemplate, dummyCtx, delimiters) : systemDefaultPerspective;
    const perspectiveInstruction = `${delimiters.blockStart('system')}${finalMemoryInstruction}${delimiters.blockEnd}`;

    const prompt = [systemPrompt, thinkPrompt, scopedHistoryBlock, perspectiveInstruction].filter(Boolean).join('\n\n');
    const stops = resolveEffectiveStopTokens(interactionData.profile?.characterStopPattern);

    const requestBody = buildGenericCompletionBody(prompt, maxTokens, interactionData.profile?.characterLanguageModelSampler || character.languageModelSampler, stops);
    const bse = getBudgetStrategyEngine();
    const { text } = await bse.generateCompletion(requestBody);
    return text || null;
}

export async function generatePeriodicCompression(
    interactionData: InteractionData,
    character: Character,
    promptBlocks: PromptBlock[],
    interval: number,
    chunkSize: number,
    maxTokens = 512,
): Promise<Context[]> {
    const history = getLocalMessageHistory(interactionData, character);
    const existingContexts = interactionData.contexts || [];
    const profile = interactionData.profile;

    const compressedRanges = new Set<string>();
    for (const context of existingContexts) {
        if (context.isAutoGenerated && context.description) {
            const match = context.description.match(/msgs:(\d+)-(\d+)/);
            if (match) compressedRanges.add(`${match[1]}-${match[2]}`);
        }
    }

    const chatMessages = history.filter((m): m is ChatMessage => m.messageType === 'chat');
    const filterFlags = getUniversalMessageFilterFlags(chatMessages, promptBlocks, interactionData.contexts || [], interactionData.locations || []);
    const visibleChatMessages = chatMessages.filter((_, i) => !filterFlags[i]);

    const newContexts: Context[] = [];
    const compressibleEnd = Math.max(0, visibleChatMessages.length - interval);

    for (let startIdx = 0; startIdx < compressibleEnd; startIdx += chunkSize) {
        const endIdx = Math.min(startIdx + chunkSize, compressibleEnd);
        const rangeKey = `${startIdx}-${endIdx}`;
        if (compressedRanges.has(rangeKey)) continue;

        const chunk = visibleChatMessages.slice(startIdx, endIdx);
        if (chunk.length === 0) continue;
        const compressed = await compressChunk(chunk, maxTokens, profile?.interactionDataSummarizationSampler, profile);
        if (!compressed) continue;

        newContexts.push(createAutoSummaryContext(`[Auto-Summary] Messages ${startIdx + 1}–${endIdx + 1}`, `msgs:${rangeKey}`, compressed, 0, maxTokens));
    }
    return newContexts;
}

export async function generateRecursiveSummary(
    interactionData: InteractionData,
    character: Character,
    promptBlocks: PromptBlock[],
    chunkSize: number,
    maxDepth: number,
    maxTokens = 1024,
): Promise<Context[]> {
    const textMessages = getLocalMessageHistory(interactionData, character, ['chat', 'whisper']) as TextMessage[];
    const existingContexts = interactionData.contexts || [];
    const profile = interactionData.profile;
    const filterFlags = getUniversalMessageFilterFlags(textMessages, promptBlocks, interactionData.contexts || [], interactionData.locations || []);
    const visibleMessages = textMessages.filter((_, i) => !filterFlags[i]);

    const fullRangeKey = `recursive-global:0-${visibleMessages.length}`;
    if (existingContexts.some(c => c.isAutoGenerated && c.description === fullRangeKey)) return [];

    const newContexts: Context[] = [];
    const layer0Summaries: string[] = [];

    for (let startIdx = 0; startIdx < visibleMessages.length; startIdx += chunkSize) {
        const endIdx = Math.min(startIdx + chunkSize, visibleMessages.length);
        const chunk = visibleMessages.slice(startIdx, endIdx);
        if (chunk.length === 0) continue;
        const compressed = await compressChunk(chunk, maxTokens, profile?.interactionDataSummarizationSampler, profile);
        if (!compressed) continue;
        layer0Summaries.push(compressed);
        newContexts.push(createAutoSummaryContext(`[Recursive L0] Messages ${startIdx + 1}–${endIdx}`, `recursive-l0:${startIdx}-${endIdx}`, compressed, 2, maxTokens));
    }

    if (layer0Summaries.length === 0) return newContexts;

    let currentLayer = layer0Summaries;
    let depth = 0;

    while (depth < maxDepth && currentLayer.length > 1) {
        depth++;
        const nextLayer: string[] = [];
        for (let i = 0; i < currentLayer.length; i += 2) {
            const batch = currentLayer.slice(i, Math.min(i + 2, currentLayer.length));
            const stops = resolveEffectiveStopTokens(profile?.interactionDataSummarizationStopPattern);
            const prompt = `${RECURSIVE_MERGE_PROMPT}\n\nSegments to merge:\n${batch.map((s, idx) => `Segment ${idx + 1}: ${s}`).join('\n\n')}\n\nMerged paragraph:`;
            const req = buildGenericCompletionBody(prompt, maxTokens, profile?.interactionDataSummarizationSampler, stops);
            const bse = getBudgetStrategyEngine();
            const { text: merged } = await bse.generateCompletion(req);
            if (merged) {
                nextLayer.push(merged);
                newContexts.push(createAutoSummaryContext(`[Recursive L${depth}] Merged segment ${Math.floor(i / 2) + 1}`, `recursive-l${depth}:segment-${Math.floor(i / 2)}`, merged, 2 + depth, maxTokens));
            }
        }
        currentLayer = nextLayer;
    }

    if (currentLayer.length >= 1) {
        newContexts.push(createAutoSummaryContext("[Recursive Global] Full conversation summary", fullRangeKey, currentLayer[0], 0, maxTokens));
    }
    return newContexts;
}

export async function generateEntropyPruningSummaries(
    interactionData: InteractionData,
    character: Character,
    promptBlocks: PromptBlock[],
    modelId: string,
    maxTokens = 256,
    chunkSize = 3,
    threshold = 0.35,
    maxRawTokens = 2000,
): Promise<Map<string, string>> {
    const results = new Map<string, string>();
    const textMessages = getLocalMessageHistory(interactionData, character, ['chat', 'whisper']) as TextMessage[];
    const filterFlags = getUniversalMessageFilterFlags(textMessages, promptBlocks, interactionData.contexts || [], interactionData.locations || []);
    const visibleMessages = textMessages.filter((_, i) => !filterFlags[i]);

    const msgLocMap = new Map<string, string>();
    for (const [locId, msgs] of Object.entries(interactionData.interactionHistories || {})) {
        for (const msg of msgs) msgLocMap.set(msg.id, locId);
    }

    const candidates = visibleMessages.map(m => ({ id: m.id, textContent: m.textContent, locationId: msgLocMap.get(m.id) }));
    const cutoffIndex = await calculateEntropyPruningCutoff(candidates, chunkSize, threshold, maxRawTokens);

    const profile = interactionData.profile;
    for (let i = 0; i < cutoffIndex; i++) {
        const msg = visibleMessages[i];
        if ((msg as ChatMessage).modelTextContentSummaries?.[modelId] || !msg.textContent) continue;
        const summary = await generateMessageSummary(msg, maxTokens, profile?.interactionDataSummarizationSampler, profile);
        if (summary) results.set(msg.id, summary);
    }

    return results;
}

export function checkTriggerThreshold(
    interactionData: InteractionData,
    currentNumberOfTokens: number,
    languageModelContextLength: number
) {
    const activeSteps = [...(interactionData.profile?.summarizationSteps || [])].filter(s => s.enabled).sort((a, b) => a.order - b.order);
    return activeSteps.filter(step => {
        const threshold = step.triggerTokenThreshold ?? 0;
        const effective = threshold > 0 ? threshold : Math.floor(languageModelContextLength * 0.7);
        return currentNumberOfTokens >= effective;
    });
}